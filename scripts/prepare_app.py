# Review renders that sit beside published assets but are never fetched.
# Patterns match paths relative to `assets/runtime`.
UNPUBLISHED_PATTERNS = (
    "crew/browser-*.png",
    "crew/looks/views",
    "equipment/browser-review.png",
    "equipment/contact-sheet.png",
)
ASSET_REFERENCE = re.compile(r'"/assets/([^"?#]+)')


def _unpublished(relative: str) -> bool:
    parts = relative.split("/")
    return any(
        fnmatch.fnmatch("/".join(parts[: len(pattern.split("/"))]), pattern)
        for pattern in UNPUBLISHED_PATTERNS
    )


def _copy_published(runtime: Path, public_assets: Path) -> None:
    for entry in PUBLISHED_RUNTIME:
        source = runtime / entry
        target = public_assets / entry
        if source.is_file():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
        elif source.is_dir():
            def ignore(folder, names, _entry=entry, _source=source):
                base = Path(folder).relative_to(runtime).as_posix()
                return [n for n in names if _unpublished(f"{base}/{n}")]
            shutil.copytree(source, target, ignore=ignore, dirs_exist_ok=True)
        else:
            raise FileNotFoundError(f"Published runtime entry missing: {entry}")


def check_references(public_assets: Path) -> None:
    """Every `/assets/...` path a published manifest names must itself be published."""
    missing = set()
    for manifest in public_assets.rglob("*.json"):
        for match in ASSET_REFERENCE.finditer(manifest.read_text(errors="ignore")):
            target = public_assets / match.group(1)
            if not target.exists():
                missing.add(f"{manifest.relative_to(public_assets)} -> /assets/{match.group(1)}")
    if missing:
        raise RuntimeError("Published manifests reference unpublished assets:\n" + "\n".join(sorted(missing)))


def prepare(app: str, root: Path = ROOT) -> None:
    if app not in PUBLIC_HELP:
        raise ValueError("Unknown app")
    public = root / "apps" / app / "public"
    public.mkdir(parents=True, exist_ok=True)
    # Remove generated legacy copies, never repository source documents.
    # Clear the previous build too, until the independent app build replaces it.
    for output in (public, root / "apps" / app / "dist"):
        for name in ("docs", "reference", "help", "PIVOT.md"):
            path = output / name
            if path.is_symlink() or path.is_file():
                path.unlink()
            elif path.is_dir():
                shutil.rmtree(path)
    # Rebuild the published tree from scratch so withdrawn assets do not linger.
    public_assets = public / "assets"
    if public_assets.is_symlink() or public_assets.is_file():
        public_assets.unlink()
    elif public_assets.is_dir():
        shutil.rmtree(public_assets)
    _copy_published(root / "assets/runtime", public_assets)
    if app == "dashboard":
        for source, destination in EDITOR_NATIVE_ASSETS.items():
            target = public / destination
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(root / source, target)
    check_references(public_assets)
    for source, destination in PUBLIC_HELP[app].items():
        target = public / destination
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(root / source, target)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("app", choices=PUBLIC_HELP)
    prepare(parser.parse_args().app)
    print("Prepared published runtime assets and allowlisted public help only.")
