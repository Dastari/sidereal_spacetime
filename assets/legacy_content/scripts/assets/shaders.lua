local function pick_space_background_uniform_schema(keys)
  local uniforms = {}
  for _, key in ipairs(keys) do
    uniforms[key] = clone_shader_field_schema(
      space_background_uniform_schema[key],
      space_background_uniform_bindings[key],
      key
    )
  end
  return uniforms
end

local function bind_shader_uniform_schema(uniforms, bindings, descriptions)
  local out = {}
  for key, field in pairs(uniforms) do
    if field.description == nil and descriptions and descriptions[key] ~= nil then
      field.description = descriptions[key]
    end
    out[key] = clone_shader_field_schema(field, bindings and bindings[key], key)
  end
  return out
end

