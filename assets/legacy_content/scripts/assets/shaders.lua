-- Apply authored descriptions in place so the schema tables carry a real
-- description for every field before they are cloned for asset editor schemas.
local function apply_field_descriptions(schema, descriptions)
  for field_key, field in pairs(schema) do
    if field.description == nil and descriptions[field_key] ~= nil then
      field.description = descriptions[field_key]
    end
  end
end

apply_field_descriptions(space_background_uniform_schema, space_background_field_descriptions)

local function clone_shader_field_schema(field, binding, field_key)
  local cloned = {}
  for key, value in pairs(field) do
    cloned[key] = value
  end
  if cloned.description == nil then
    cloned.description = default_shader_field_description(field_key, field)
  end
  if binding then
    cloned.uniform = binding.uniform
    cloned.components = binding.components
    cloned.control = binding.control or cloned.control
  end
  return cloned
end

